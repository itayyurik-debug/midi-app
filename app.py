# 2. ADVANCED ACOUSTIC & HARMONIC CLEANUP
# ==========================================
def filter_noise_and_ghost_notes(notes, min_duration=0.035, min_velocity=12, max_duration=4.5):
    """Filters transient acoustic noise, zero-velocity hits, and caps pedal-smeared notes."""
    out = []
    for pitch, start, end, vel in notes:
        dur = end - start
        if dur < min_duration or vel < min_velocity:
            continue
        if dur > max_duration:
            end = start + max_duration
        out.append((pitch, start, end, vel))
    return out


def remove_octave_overtones(notes, time_tolerance=0.045):
    """Removes ghost harmonic overtones generated by bass string resonance (12/24 semitones higher)."""
    out = []
    for i, (pitch, start, end, vel) in enumerate(notes):
        is_overtone = False
        for j, (pitch2, start2, end2, vel2) in enumerate(notes):
            if i == j or pitch2 == pitch:
                continue
            if (pitch - pitch2) in (12, 24) and abs(start - start2) <= time_tolerance and (end - start) <= (end2 - start2) + time_tolerance:
                is_overtone = True
                break
        if not is_overtone:
            out.append((pitch, start, end, vel))
    return out


# ==========================================
# 3. COMMERCIAL SHEET-MUSIC PARSING ENGINE
# ==========================================
def merge_micro_gaps(notes, max_gap_sec=0.065):
    """
    Commercial-grade feature: Merges repeated notes with micro gaps (< 65ms).
    This eliminates ugly ties (~) and 1/32 rest clutter in sheet music apps.
    """
    if not notes:
        return []
    
    sorted_notes = sorted(notes, key=lambda x: (x[0], x[1]))
    merged = []
    
    curr_pitch, curr_s, curr_e, curr_v = sorted_notes[0]
    for n_pitch, n_s, n_e, n_v in sorted_notes[1:]:
        if n_pitch == curr_pitch and (n_s - curr_e) <= max_gap_sec:
            curr_e = max(curr_e, n_e)
            curr_v = max(curr_v, n_v)
        else:
            merged.append((curr_pitch, curr_s, curr_e, curr_v))
            curr_pitch, curr_s, curr_e, curr_v = n_pitch, n_s, n_e, n_v
    merged.append((curr_pitch, curr_s, curr_e, curr_v))
    
    return sorted(merged, key=lambda x: x[1])


def resolve_pitch_overlaps(notes):
    """Truncates note tails if a new note of the same pitch is pressed before the tail ends."""
    sorted_notes = sorted(notes, key=lambda x: (x[0], x[1]))
    cleaned = []
    for i in range(len(sorted_notes)):
        p, s, e, v = sorted_notes[i]
        for j in range(i + 1, len(sorted_notes)):
            p2, s2, e2, v2 = sorted_notes[j]
            if p2 == p:
                if s2 < e:
                    e = s2
                break
            elif p2 > p:
                break
        if e > s + 0.03:
            cleaned.append((p, s, e, v))
    return sorted(cleaned, key=lambda x: x[1])


def quantize_for_sheet_music(notes, bpm, grid_division=16):
    """
    Rhythmic Quantization Engine:
    Snaps starts and ends to a musical grid (1/16th notes = 120 ticks at 480 PPQ)
    and enforces minimum note lengths so sheet music notation stays clean.
    """
    grid_ticks = PPQ_OUT // (grid_division // 4)
    sec_per_tick = 60.0 / (bpm * PPQ_OUT)
    
    quantized = []
    for pitch, start_sec, end_sec, vel in notes:
        s_tick = int(start_sec / sec_per_tick)
        e_tick = int(end_sec / sec_per_tick)
        
        q_start = round(s_tick / grid_ticks) * grid_ticks
        q_end = round(e_tick / grid_ticks) * grid_ticks
        
        if q_end <= q_start:
            q_end = q_start + grid_ticks
            
        dur_ticks = q_end - q_start
        quantized.append((pitch, max(0, q_start), dur_ticks, vel))
        
    return quantized


def smart_clef_hand_split(quantized_notes):
    """Splits notes smoothly into Right Hand (Treble) and Left Hand (Bass) at C4."""
    right_hand, left_hand = [], []
    for pitch, s_tick, d_tick, vel in quantized_notes:
        if pitch >= 60:
            right_hand.append((pitch, s_tick, d_tick, vel))
        else:
            left_hand.append((pitch, s_tick, d_tick, vel))
    return right_hand, left_hand


def detect_bpm_from_audio(wav_path):
    import numpy as np
    import librosa
    y, sr = librosa.load(wav_path, sr=None)
    tempo, _ = librosa.beat.beat_track(y=y, sr=sr)
    return float(np.atleast_1d(tempo)[0])


