@app.post("/transcribe")
async def transcribe(
    file: UploadFile = File(...),
    split_hands: bool = Form(True),
    reference_midi: UploadFile = File(None),
):
    import uuid
    job_id = uuid.uuid4().hex[:8]
    src_ext = os.path.splitext(file.filename or "")[1] or ".mp3"
    raw_path = f"uploads/{job_id}_raw{src_ext}"
    stem_wav_path = f"uploads/{job_id}_stem.wav"
    output_midi = f"outputs/{job_id}.mid"
    final_midi = f"outputs/{job_id}_final.mid"
    sep_dir = f"outputs/{job_id}_sep"

    # גזירת השם המקורי של הקובץ בלי הסיומת .mp3
    orig_stem = os.path.splitext(file.filename or "transcribed")[0] or "transcribed"
    download_name = f"{orig_stem}.mid"

    try:
        with open(raw_path, "wb") as f:
            shutil.copyfileobj(file.file, f)

        # 1. Demucs Stem Isolation
        demucs_result = subprocess.run(
            ["demucs", "-n", "htdemucs_6s", "-o", sep_dir, raw_path],
            capture_output=True, text=True,
        )
        if demucs_result.returncode != 0:
            raise HTTPException(status_code=500, detail=f"הפרדת Demucs נכשלה: {demucs_result.stderr[-1000:]}")

        raw_stem_name = os.path.splitext(os.path.basename(raw_path))[0]
        stem_source = os.path.join(sep_dir, "htdemucs_6s", raw_stem_name, "piano.wav")
        if not os.path.exists(stem_source):
            raise HTTPException(status_code=500, detail="סטם הפסנתר לא נמצא לאחר ההפרדה")

        conv = subprocess.run(["ffmpeg", "-y", "-i", stem_source, "-ar", "32000", "-ac", "1", stem_wav_path], capture_output=True, text=True)
        if conv.returncode != 0:
            raise HTTPException(status_code=500, detail="המרה ל-WAV נכשלה")

        # 2. Piano Transcription Engine
        if PIANO_MODEL is not None:
            from piano_transcription_inference import sample_rate
            import librosa
            audio, _ = librosa.load(stem_wav_path, sr=sample_rate)
            PIANO_MODEL.transcribe(audio, output_midi)
        else:
            from basic_pitch.inference import predict_and_save
            predict_and_save([stem_wav_path], "outputs", True, False, False, False)
            output_midi = f"outputs/{job_id}_stem_basic_pitch.mid"

        if not os.path.exists(output_midi):
            raise HTTPException(status_code=500, detail="קובץ ה-MIDI לא נוצר")

        # 3. Read Raw Notes
        raw_notes = read_midi_notes_and_map(output_midi)["notes"]
        
        # 4. Sheet-Music Post-Processing Pipeline
        cleaned = filter_noise_and_ghost_notes(raw_notes, min_duration=0.035, min_velocity=12)
        cleaned = remove_octave_overtones(cleaned)
        cleaned = merge_micro_gaps(cleaned, max_gap_sec=0.065)
        cleaned = resolve_pitch_overlaps(cleaned)
        
        if not cleaned:
            raise HTTPException(status_code=500, detail="לא נותרו תווים לאחר סינון רעשים")

        # 5. BPM & Rhythmic Grid Quantization
        if reference_midi is not None:
            ref_bytes = await reference_midi.read()
            ref_path = f"uploads/{job_id}_ref.mid"
            with open(ref_path, "wb") as f:
                f.write(ref_bytes)
            anchor = read_midi_notes_and_map(ref_path)
            detected_bpm = anchor["tempo_map"][0][1] if anchor["tempo_map"] else 120.0
        else:
            detected_bpm = detect_bpm_from_audio(raw_path)

        quantized_notes = quantize_for_sheet_music(cleaned, bpm=detected_bpm, grid_division=16)

        # 6. Build Final Sheet-Music Ready MIDI
        final_bytes = build_output_midi_bytes(quantized_notes, bpm=detected_bpm, split_hands=bool(split_hands))
        with open(final_midi, "wb") as f:
            f.write(final_bytes)

        return FileResponse(final_midi, filename=download_name, media_type="audio/midi")

    except HTTPException:
        raise
    except Exception as err:
        print(f"❌ שגיאה בזמן המרה: {err}")
        raise HTTPException(status_code=500, detail=str(err))
    finally:
        gc.collect()
        if torch.cuda.is_available():
            torch.cuda.empty_cache()
