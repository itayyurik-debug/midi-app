def build_track(notes, channel=0):
    tr = mido.MidiTrack()
    evs = []
    for pitch, s_tick, d_tick, vel in notes:
        evs.append((s_tick, mido.Message("note_on", note=int(pitch), velocity=int(vel), channel=channel)))
        evs.append((s_tick + d_tick, mido.Message("note_off", note=int(pitch), velocity=0, channel=channel)))
    evs.sort(key=lambda e: e[0])
    
    last_t = 0
    for tick, msg in evs:
        msg.time = max(0, round(tick - last_t))
        tr.append(msg)
        last_t = max(last_t, tick)
    tr.append(mido.MetaMessage("end_of_track"))
    return tr


def build_output_midi_bytes(quantized_notes, bpm, split_hands=True):
    out_mid = mido.MidiFile(ticks_per_beat=PPQ_OUT)
    
    meta_track = mido.MidiTrack()
    meta_track.append(mido.MetaMessage("set_tempo", tempo=mido.bpm2tempo(bpm), time=0))
    meta_track.append(mido.MetaMessage("time_signature", numerator=4, denominator=4, time=0))
    meta_track.append(mido.MetaMessage("end_of_track", time=0))
    out_mid.tracks.append(meta_track)

    if split_hands:
        rh, lh = smart_clef_hand_split(quantized_notes)
        out_mid.tracks.append(build_track(rh, channel=0))
        out_mid.tracks.append(build_track(lh, channel=1))
    else:
        out_mid.tracks.append(build_track(quantized_notes, channel=0))

    buf = io.BytesIO()
    out_mid.save(file=buf)
    return buf.getvalue()


